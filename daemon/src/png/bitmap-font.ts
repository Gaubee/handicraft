/** 点阵缩放档（round(fontPx/7)，最小 1——离散点阵非整数缩放会破形）。 */
export function asciiScaleOf(fontPx: number): number {
  return Math.max(1, Math.round(fontPx / 7));
}

/** 单串 ASCII 文本点阵宽度（scale 倍；每字步进 6 点）。 */
export function measureAscii(text: string, scale: number): { width: number; height: number } {
  if (text.length === 0) return { width: 0, height: 7 * scale };
  const units = text.length * 6 - 1; // 尾字无间距
  return { width: units * scale, height: 7 * scale };
}

/** 字符点亮像素数（scale² 前的点数——测试对账用）。 */
export function litPixelsOf(text: string): number {
  let count = 0;
  for (const char of text) {
    const glyph = GLYPHS[char];
    if (glyph === undefined) continue;
    for (const row of glyph) {
      for (const cell of row) {
        if (cell === '1') count += 1;
      }
    }
  }
  return count;
}

/**
 * 点阵文本绘制（整数 scale；左上角 (x,y)——水平垂直都按目标盒居中由调用方算偏移）。
 * alpha 为绘制强度（1=实心；编号用 1，图例用 1）。越界剪裁。
 */
export function drawAsciiText(
  plane: { width: number; height: number; set(x: number, y: number, alpha: number): void },
  text: string,
  x: number,
  y: number,
  scale: number,
): void {
  for (let i = 0; i < text.length; i++) {
    const glyph = GLYPHS[text[i]!];
    if (glyph === undefined) continue; // 未收录字符由调用方先行分派（cjk/方框）
    for (let row = 0; row < 7; row++) {
      const line = glyph[row]!;
      for (let col = 0; col < 5; col++) {
        if (line[col] !== '1') continue;
        for (let dy = 0; dy < scale; dy++) {
          for (let dx = 0; dx < scale; dx++) {
            plane.set(x + (i * 6 + col) * scale + dx, y + row * scale + dy, 1);
          }
        }
      }
    }
  }
}

/**
 * 混排文本绘制：ASCII 走点阵（确定性），非 ASCII 走 cjkGlyphDrawer（系统字体
 * 栅格位图——numbered-sheet 注入 rasterizeCjk 的绑定面），再降级=空心方框
 * （sizePx 见方——信息缺失可见而非静默空白）。返回绘制宽度。
 */
export function drawMixedText(
  plane: { width: number; height: number; set(x: number, y: number, alpha: number): void },
  text: string,
  x: number,
  y: number,
  fontPx: number,
  cjkDrawer: (char: string, drawX: number, drawY: number, sizePx: number) => boolean,
): { width: number } {
  let cursor = x;
  const asciiScale = asciiScaleOf(fontPx);
  for (const char of text) {
    if (GLYPHS[char] !== undefined) {
      drawAsciiText(plane, char, cursor, y + Math.round((fontPx - 7 * asciiScale) / 2), asciiScale);
      cursor += 6 * asciiScale;
      continue;
    }
    if (cjkDrawer(char, cursor, y, Math.round(fontPx))) {
      cursor += Math.round(fontPx);
      continue;
    }
    drawFallbackBox(plane, cursor, y, Math.round(fontPx));
    cursor += Math.round(fontPx);
  }
  return { width: cursor - x };
}

/** 未收录字符的空心方框（宽=字高——可见占位，不静默丢字）。 */
export function drawFallbackBox(
  plane: { width: number; height: number; set(x: number, y: number, alpha: number): void },
  x: number,
  y: number,
  sizePx: number,
): void {
  const w = Math.max(2, Math.round(sizePx * 0.8));
  const h = Math.max(2, Math.round(sizePx));
  for (let dx = 0; dx < w; dx++) {
    plane.set(x + dx, y, 1);
    plane.set(x + dx, y + h - 1, 1);
  }
  for (let dy = 0; dy < h; dy++) {
    plane.set(x, y + dy, 1);
    plane.set(x + w - 1, y + dy, 1);
  }
}

/** 混排文本测量（宽度口径与 drawMixedText 一致）。 */
export function measureMixedText(text: string, fontPx: number, cjkMeasure: (char: string) => boolean): { width: number; height: number } {
  let width = 0;
  const asciiScale = asciiScaleOf(fontPx);
  for (const char of text) {
    if (GLYPHS[char] !== undefined) {
      width += 6 * asciiScale;
      continue;
    }
    width += Math.max(2, Math.round(fontPx * (cjkMeasure(char) ? 1 : 0.8)));
  }
  return { width, height: Math.round(fontPx) };
}
